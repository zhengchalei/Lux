//! build.rs embeds the bundled champion portraits into the native executable.
//! Portrait identifiers are generated from filenames so the application can load
//! images without relying on its launch directory or shipping a companion assets
//! folder. Rebuilding tracks changes to the portrait directory.

use std::{env, fs, path::PathBuf};

/// main generates a sorted portrait table from the checked-in JPEG assets.
fn main() {
    println!("cargo:rerun-if-changed=assets/portraits");
    let directory =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap()).join("assets/portraits");
    let mut entries: Vec<_> = fs::read_dir(directory)
        .unwrap()
        .filter_map(Result::ok)
        .filter_map(|e| {
            let path = e.path();
            let id = path.file_stem()?.to_str()?.parse::<u32>().ok()?;
            Some((id, path))
        })
        .collect();
    entries.sort_by_key(|e| e.0);
    let rows = entries
        .iter()
        .map(|(id, path)| format!("({id},include_bytes!(r#\"{}\"#)),", path.display()))
        .collect::<String>();
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("portraits.rs"),
        format!("// Generated by build.rs.\npub const PORTRAITS: &[(u32, &[u8])] = &[{rows}];"),
    )
    .unwrap();
}
